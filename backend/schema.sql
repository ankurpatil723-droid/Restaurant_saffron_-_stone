-- Supabase SQL Schema for Restaurant Project
-- You can run this directly in your Supabase SQL Editor:
-- Dashboard -> SQL Editor -> New query -> Paste & Run

-- 1. Create 'todos' table (optional, matching Supabase quickstart)
CREATE TABLE IF NOT EXISTS public.todos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  is_complete BOOLEAN DEFAULT FALSE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Create 'orders' table for storing customer restaurant orders
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT UNIQUE NOT NULL,
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  order_type TEXT NOT NULL,
  address TEXT,
  landmark TEXT,
  email TEXT,
  notes TEXT,
  customer_request TEXT,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal NUMERIC(10, 2) NOT NULL,
  discount NUMERIC(10, 2) DEFAULT 0,
  tax NUMERIC(10, 2) NOT NULL,
  total NUMERIC(10, 2) NOT NULL,
  payment_method TEXT DEFAULT 'COD',
  payment_status TEXT DEFAULT 'pending',
  status TEXT DEFAULT 'placed',
  status_history JSONB DEFAULT '[]'::jsonb,
  placed_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  promised_by TIMESTAMP WITH TIME ZONE,
  delivery_confirmed BOOLEAN DEFAULT FALSE,
  delivery_confirmed_at TIMESTAMP WITH TIME ZONE,
  tracking_token TEXT,
  dest_lat NUMERIC(10, 6),
  dest_lng NUMERIC(10, 6),
  driver_lat NUMERIC(10, 6),
  driver_lng NUMERIC(10, 6),
  driver_updated_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- Allow public read/insert on todos
CREATE POLICY "Allow public read on todos" ON public.todos FOR SELECT USING (true);
CREATE POLICY "Allow public insert on todos" ON public.todos FOR INSERT WITH CHECK (true);

-- Allow public order creation (anon) and admin full access (service_role)
CREATE POLICY "Allow anon insert orders" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow service role full access on orders" ON public.orders FOR ALL USING (auth.role() = 'service_role');
